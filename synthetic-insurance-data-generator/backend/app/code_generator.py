def generate_number(path: str, schema: dict[str, Any], integer: bool) -> int | float:
    name = path.lower()
    minimum = schema.get("minimum", schema.get("exclusiveMinimum", 0 if any(k in name for k in ["premium", "limit", "deductible", "amount", "age", "year"]) else 1))
    maximum = schema.get("maximum", None)
    if maximum is None:
        if "deductible" in name:
            maximum = 5000
        elif "limit" in name:
            maximum = 1000000
        elif "premium" in name:
            maximum = 12000
        elif "year" in name:
            minimum, maximum = 1990, date.today().year + 1
        else:
            maximum = max(float(minimum) + 100, 1000)
    value = random.uniform(float(minimum), float(maximum))
    return int(round(value)) if integer else round(value, 2)


