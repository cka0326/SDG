def generate_value(schema: dict[str, Any], path: str, context: dict[str, Any]) -> Any:
    if not isinstance(schema, dict):
        return None
    if "enum" in schema:
        return random.choice(schema["enum"])
    typ = schema.get("type")
    if isinstance(typ, list):
        if "null" in typ and random.random() < 0.15:
            return None
        typ = next((t for t in typ if t != "null"), typ[0])
    if typ is None and "properties" in schema:
        typ = "object"
    if typ == "object":
        required = set(schema.get("required", []))
        obj = {{}}
        for name, child in schema.get("properties", {{}}).items():
            if name not in required and random.random() < 0.18:
                continue
            obj[name] = generate_value(child, join_path(path, name), obj)
        return obj
    if typ == "array":
        min_items = int(schema.get("minItems", 1))
        max_items = int(schema.get("maxItems", max(min_items, 3)))
        max_items = max(min_items, min(max_items, 5))
        return [generate_value(schema.get("items", {{"type": "string"}}), path + "[]", context) for _ in range(random.randint(min_items, max_items))]
    if typ in ("integer", "number"):
        return generate_number(path, schema, integer=(typ == "integer"))
    if typ == "boolean":
        return random.choice([True, False])
    return generate_string(path, schema)


