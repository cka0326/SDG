def find_key_path(value: Any, target: str, base: list[Any] | None = None) -> list[Any] | None:
    base = base or []
    if isinstance(value, dict):
        for key, child in value.items():
            if key.lower() == target.lower():
                return base + [key]
            found = find_key_path(child, target, base + [key])
            if found:
                return found
    if isinstance(value, list):
        for i, child in enumerate(value):
            found = find_key_path(child, target, base + [i])
            if found:
                return found
    return None


def set_path(value: Any, path: list[Any], new_value: Any) -> None:
    node = value
    for part in path[:-1]:
        node = node[part]
    node[path[-1]] = new_value


def join_path(prefix: str, name: str) -> str:
    return f"{{prefix}}.{{name}}" if prefix else name


def flatten(record: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    out = {{}}
    for key, value in record.items():
        full_key = f"{{prefix}}.{{key}}" if prefix else key
        if isinstance(value, dict):
            out.update(flatten(value, full_key))
        elif isinstance(value, list):
            out[full_key] = json.dumps(value)
        else:
            out[full_key] = value
    return out


def write_output(records: list[dict[str, Any]], output_format: str, output: Path) -> None:
    if output_format == "json":
        output.write_text(json.dumps(records, indent=2), encoding="utf-8")
    elif output_format == "jsonl":
        output.write_text("\\n".join(json.dumps(r) for r in records), encoding="utf-8")
    else:
        rows = [flatten(r) for r in records]
        fieldnames = sorted({{k for row in rows for k in row}})
        with output.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(rows)


